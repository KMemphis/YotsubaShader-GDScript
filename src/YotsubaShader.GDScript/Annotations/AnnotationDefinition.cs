using YotsubaShader.IR.Intermediate;
using YotsubaShader.IR.Intermediate.Slot.Types;

namespace YotsubaShader.GDScript.Annotations;

/// <summary>The canonical meaning of an annotation, independent of which vocabulary spelled it.</summary>
public enum AnnotationKind
{
    /// <summary><c>@vertex</c>, <c>@fragment</c>, <c>@compute</c>.</summary>
    Stage,
    /// <summary>Three positive integers.</summary>
    WorkgroupSize,
    /// <summary>One integer: <c>LocationSlot</c>.</summary>
    Location,
    /// <summary>A fixed built-in value: <c>BuiltInSlot</c>.</summary>
    BuiltIn,
    /// <summary><c>@builtin(name)</c>: the built-in is named by the argument.</summary>
    BuiltInByName,
    /// <summary>A vertex semantic with an optional index: <c>VertexSlot</c>.</summary>
    VertexSemantic,
    /// <summary><c>@semantic("POSITION", 0)</c>: the usage is named by the first argument.</summary>
    VertexSemanticByName,
    /// <summary><c>@group(n)</c>.</summary>
    Group,
    /// <summary><c>@binding(n)</c>.</summary>
    Binding,
    /// <summary><c>@register("b", n)</c> (HLSL): sets binding n in set 0.</summary>
    Register,
    Uniform,
    StorageBuffer,
    PushConstant,
    /// <summary>Known to Yotsuba's vocabularies but not representable in the IR yet.</summary>
    NotSupportedYet
}

/// <summary>One entry of the annotation vocabulary table.</summary>
public sealed record AnnotationDefinition(
    string Name,
    AnnotationKind Kind,
    string Dialect,
    Stage Stage = Stage.None,
    BuiltIn? BuiltIn = null,
    VertexUsage? Usage = null,
    string? Note = null);
